const express = require("express");
const router = express.Router();
const Constructor = require("../models/constructors");

const FETCH_OPTIONS = {
  headers: {
    "User-Agent": "Mozilla/5.0 Express-F1/1.0",
    Accept: "application/json",
  },
};

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/* GET constructors listing with search and sorting */
router.get("/", async (req, res) => {
  try {
    const { search, sort = "wins_desc" } = req.query;
    const filter = {};
    if (search) {
      filter.$or = [
        { name: { $regex: search, $options: "i" } },
        { nationality: { $regex: search, $options: "i" } },
        { _id: { $regex: search, $options: "i" } },
      ];
    }
    const sortOption = {};
    if (sort === "wins_desc") sortOption.total_wins = -1;
    else if (sort === "titles_desc") sortOption["championships.championships_wins"] = -1;
    else if (sort === "name_asc") sortOption.name = 1;
    else if (sort === "debut_asc") sortOption.debut_year = 1;
    else sortOption.total_wins = -1;

    const constructors = await Constructor.find(filter).sort(sortOption);
    res.json({ result: true, count: constructors.length, constructors });
  } catch (error) {
    res.status(500).json({ result: false, error: error.message });
  }
});

/* =========================================================
   PASSE 1 : Création de la base des écuries (API Ergast)
   Endpoint: /constructors/seed/base
   ========================================================= */
router.get("/seed/base", async (req, res) => {
  try {
    console.log("➡️ Passe 1 : Récupération des écuries de base...");
    let offset = 0;
    const limit = 100;
    let hasMore = true;
    let totalConstructors = 0;

    while (hasMore) {
      // Utilisation de la concaténation classique au lieu des backticks
      const url = `https://api.jolpi.ca/ergast/f1/constructors.json?limit=${limit}&offset=${offset}`;
      const response = await fetch(url, FETCH_OPTIONS);

      if (response.status === 429) {
        console.log("⚠️ Rate limit, pause...");
        await sleep(2000);
        continue;
      }

      // Ajout d'une vérification explicite
      if (!response.ok) {
        throw new Error("Erreur HTTP " + response.status + " sur l'URL " + url);
      }

      const data = await response.json();
      const constructorsList = data.MRData.ConstructorTable.Constructors;

      if (constructorsList.length === 0) {
        hasMore = false;
        break;
      }

      const baseOperations = constructorsList.map((c) => ({
        updateOne: {
          filter: { _id: c.constructorId },
          update: {
            $setOnInsert: {
              name: c.name,
              nationality: c.nationality,
              debut_year: null, // Place réservée pour la Passe 2
              total_wins: 0, // Place réservée pour la Passe 3
              championships: {
                championships_wins: 0,
                championship_years: [],
              },
            },
          },
          upsert: true,
        },
      }));

      await Constructor.bulkWrite(baseOperations);
      totalConstructors += constructorsList.length;
      offset += limit;

      await sleep(300);
    }

    console.log(
      "✅ Passe 1 terminée : " +
        totalConstructors +
        " écuries vérifiées/créées.",
    );
    res.json({
      message:
        "✅ Passe 1 terminée : " +
        totalConstructors +
        " écuries vérifiées/créées.",
    });
  } catch (error) {
    console.error("🛑 Erreur Passe 1 :", error);
    res.status(500).json({ error: error.message });
  }
});

